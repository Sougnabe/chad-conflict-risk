"""
Generate notebooks/capstone_pipeline.ipynb from the pipeline scripts and the package source.

The scripts and the chadrisk package remain the single source of truth. The notebook runs each
step (the script code, adapted for a notebook: fixed arguments instead of the command line,
optional steps behind a flag) and ends with the full source code of the package, for reading.

Usage:
    python scripts/make_notebook.py
    python -m nbconvert --to notebook --execute --inplace notebooks/capstone_pipeline.ipynb
"""

import re
from pathlib import Path

import nbformat as nbf

ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ROOT / "scripts"
PACKAGE = ROOT / "chadrisk"
OUT = ROOT / "notebooks" / "capstone_pipeline.ipynb"

STEPS = [
    ("download_acled.py", "1. Download conflict events (ACLED API)", "RUN_DOWNLOAD"),
    ("build_target.py", "2. Validated labels and target variable", None),
    ("eda_acled.py", "3. Exploratory analysis", None),
    ("build_panel.py", "4. Department x month panel", None),
    ("init_db.py", "5. Dashboard database", None),
    ("gee_extract.py", "6. Satellite indicators (Google Earth Engine)", "RUN_GEE"),
    ("build_features.py", "7. Feature table (no look-ahead)", None),
]
TRAINING_RUNS = [
    ("Research model, quarterly", ["--mode", "research", "--unit", "quarter"]),
    ("Research model, monthly", ["--mode", "research", "--unit", "month"]),
    ("Operational model, quarterly (dashboard outlook)",
     ["--mode", "operational", "--unit", "quarter", "--fixed-model", "logreg_OB"]),
    ("Operational model, monthly", ["--mode", "operational", "--unit", "month"]),
]

INTRO = """# Farmer-Herder Conflict Risk in Southern Chad — Full Pipeline

Capstone project, BSc Software Engineering (Machine Learning), African Leadership University.

This notebook runs the complete pipeline, step by step, with its outputs, and ends with the
full source code of the `chadrisk` package. It is generated by `scripts/make_notebook.py` from
the scripts and the package, which remain the reference implementation.

**Research question.** Do satellite-derived indicators of pasture conditions, rainfall and the
crop calendar improve the prediction of farmer-herder conflict risk in southern Chad, compared
with conflict history alone?

**Steps**
1. Download conflict events (ACLED API) — *skipped by default, data already downloaded*
2. Validated labels and target variable
3. Exploratory analysis
4. Department x month panel
5. Dashboard database
6. Satellite indicators (Google Earth Engine) — *skipped by default, already extracted*
7. Feature table (no look-ahead)
8. Training and evaluation: research model (conflict history up to the previous month) and
   operational model (only information available at forecast time), monthly and quarterly
9. Automated tests
10. Source code of the `chadrisk` package

> Ethics: aggregated department-level data only, no ethnic or religious variables. Raw ACLED
> data are not redistributed (licence). The tool supports human decisions; it does not make them.
"""

SETUP = """import subprocess
import sys
from pathlib import Path

# Project root (works whether the notebook is opened from notebooks/ or from the project root)
ROOT = Path.cwd().parent if Path.cwd().name == "notebooks" else Path.cwd()
sys.path.insert(0, str(ROOT))  # makes the chadrisk package importable

# Optional steps (they need credentials and take time; their outputs are already in data/)
RUN_DOWNLOAD = False   # step 1: re-download ACLED events (needs ACLED credentials in .env)
RUN_GEE = False        # step 6: update satellite indicators (needs Earth Engine)
print("Project root:", ROOT)"""


def split_docstring(src):
    m = re.match(r'\s*"""(.*?)"""\n', src, re.S)
    if not m:
        return "", src
    doc = re.split(r"\n\s*Usage:", m.group(1).strip())[0].strip()
    return doc, src[m.end():]


def adapt(code):
    """Script code -> notebook code."""
    code = re.sub(r"import _bootstrap.*\n", "", code)
    code = code.replace('matplotlib.use("Agg")', "")  # show figures inline
    code = code.replace("plt.close()", "plt.show()")
    code = code.replace("args = parser.parse_args()", "args = parser.parse_args([])")
    return code.strip("\n")


def guarded(code, flag, message):
    body = "\n".join("    " + l if l.strip() else "" for l in code.split("\n"))
    return f"if {flag}:\n{body}\nelse:\n    print({message!r})"


nb = nbf.v4.new_notebook()
nb.metadata["kernelspec"] = {"name": "python3", "display_name": "Python 3", "language": "python"}
cells = [nbf.v4.new_markdown_cell(INTRO), nbf.v4.new_code_cell(SETUP)]

for script, title, flag in STEPS:
    doc, code = split_docstring((SCRIPTS / script).read_text(encoding="utf8"))
    code = adapt(code)
    cells.append(nbf.v4.new_markdown_cell(f"## {title}\n\n```text\n{doc}\n```"))
    if flag:
        code = guarded(code, flag, f"Skipped (set {flag} = True to run this step).")
    cells.append(nbf.v4.new_code_cell(code))

cells.append(nbf.v4.new_markdown_cell(
    "## 8. Training and evaluation\n\nEach run uses `chadrisk.experiment.Experiment` "
    "(selection on 2019-2023 by rolling origin, single evaluation on 2024 - Sept 2025) and "
    "`chadrisk.reporting.ExperimentReporter` (result files, figures, dashboard predictions). "
    "The code of `scripts/train_models.py` is shown below, then run for the four "
    "configurations."))
_, train_code = split_docstring((SCRIPTS / "train_models.py").read_text(encoding="utf8"))
cells.append(nbf.v4.new_markdown_cell("```python\n" + adapt(train_code) + "\n```"))
for title, args in TRAINING_RUNS:
    cells.append(nbf.v4.new_markdown_cell(f"### {title}"))
    cells.append(nbf.v4.new_code_cell(
        f"r = subprocess.run([sys.executable, str(ROOT / 'scripts' / 'train_models.py'), "
        f"*{args!r}],\n                   capture_output=True, text=True, cwd=ROOT)\n"
        "print(r.stdout[-4000:] or r.stderr[-4000:])"))

cells.append(nbf.v4.new_markdown_cell("### Current outlook (operational model)"))
cells.append(nbf.v4.new_code_cell(
    "from chadrisk.config import PATHS\n"
    "from chadrisk.storage import RiskRepository\n\n"
    "repo = RiskRepository(PATHS.database)\n"
    "preds = repo.predictions().merge(repo.departments()[['dept_id', 'department', "
    "'province']], on='dept_id')\n"
    "outlook = preds[preds['model'].str.endswith('operational_quarter_forecast')]\n"
    "outlook = outlook.sort_values('risk', ascending=False).reset_index(drop=True)\n"
    "outlook.index += 1\n"
    "print('Quarter starting', outlook['ym'].iloc[0])\n"
    "outlook[['department', 'province', 'risk']].head(10)"))

cells.append(nbf.v4.new_markdown_cell(
    "## 9. Automated tests\n\nUnit tests (each class, on small synthetic data) and "
    "integration tests (the real pipeline outputs and the dashboard)."))
cells.append(nbf.v4.new_code_cell(
    "r = subprocess.run([sys.executable, '-m', 'pytest', '-q', '--color=no', '-p', "
    "'no:cacheprovider', str(ROOT / 'tests')],\n                   capture_output=True, "
    "text=True, cwd=ROOT)\nprint(r.stdout[-3000:])"))

cells.append(nbf.v4.new_markdown_cell(
    "## 10. Source code of the `chadrisk` package\n\nFor reading. The dashboard code is in "
    "`app/` (run with `streamlit run app/app.py`)."))
for module in sorted(PACKAGE.rglob("*.py")):
    rel = module.relative_to(ROOT).as_posix()
    cells.append(nbf.v4.new_markdown_cell(
        f"### `{rel}`\n\n```python\n{module.read_text(encoding='utf8').strip()}\n```"))

nb.cells = cells
OUT.parent.mkdir(parents=True, exist_ok=True)
nbf.write(nb, OUT)
print(f"{OUT}: {len(cells)} cells")
